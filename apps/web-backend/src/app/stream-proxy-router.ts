/**
 * Stream Proxy Router
 *
 * Proxies IPTV media streams (HLS manifests, TS segments, MP4, etc.) through
 * the server so that all stream traffic originates from the host device rather
 * than the user's browser. This solves:
 *
 *  - CORS restrictions on stream servers
 *  - Mixed-content (HTTP stream inside HTTPS app)
 *  - Geo-restriction bypass when the server is in a permitted region
 *  - Privacy: the user's IP is never sent to the stream origin
 *
 * Endpoint:  GET /stream-proxy
 * Query params:
 *   - url        (required)  The original stream URL, URL-encoded.
 *   - userAgent  (optional)  Custom User-Agent to send upstream.
 *
 * The URL must be pre-registered via POST /provider-targets so we hold a
 * validated targetId → URL mapping.  For the stream proxy we accept the raw
 * URL directly (gated by the same ProviderUrlPolicy SSRF rules) because HLS
 * segment requests are auto-generated by hls.js at runtime and cannot go
 * through the registration round-trip.
 *
 * Security notes:
 *  - Every URL is validated through `validateProviderUrl` (SSRF protection,
 *    private-network block, protocol allow-list).
 *  - Redirect hops are followed up to MAX_REDIRECT_HOPS times; each hop is
 *    re-validated.
 *  - The response is streamed (piped) so large TS segments never accumulate
 *    in memory.
 *  - Only safe response headers are forwarded to the browser.
 */

import { Request, Response, IRouter } from 'express';
import {
    request as httpRequest,
    IncomingMessage,
    RequestOptions,
} from 'node:http';
import { request as httpsRequest } from 'node:https';
import {
    ProviderUrlPolicy,
    validateProviderUrl,
} from './provider-url-policy';

/** Headers we forward from the upstream stream response to the browser. */
const FORWARDED_RESPONSE_HEADERS: ReadonlySet<string> = new Set([
    'content-type',
    'content-length',
    'content-range',
    'accept-ranges',
    'cache-control',
    'last-modified',
    'etag',
    'transfer-encoding',
]);

/** Headers the browser sends that we forward upstream (minus hop-by-hop). */
const FORWARDED_REQUEST_HEADERS: ReadonlySet<string> = new Set([
    'range',
    'if-range',
    'if-modified-since',
    'if-none-match',
]);

const MAX_REDIRECT_HOPS = 5;
const STREAM_PROXY_TIMEOUT_MS = 30_000;

export function mountStreamProxy(
    router: IRouter,
    policy: ProviderUrlPolicy
): void {
    const proxyRoute = /^\/(?:api\/)?(?:stream-proxy|live|movie|series)(?:\/.*)?$/;
    router.get(proxyRoute, (req: Request, res: Response) => {
        void handleStreamProxy(req, res, policy);
    });
    router.head(proxyRoute, (req: Request, res: Response) => {
        void handleStreamProxy(req, res, policy);
    });
}

async function handleStreamProxy(
    req: Request,
    res: Response,
    policy: ProviderUrlPolicy
): Promise<void> {
    const rawUrl =
        typeof req.query['url'] === 'string' ? req.query['url'].trim() : '';

    if (!rawUrl) {
        res.status(400).json({ message: 'Missing url parameter', status: 400 });
        return;
    }

    const userAgent =
        typeof req.query['userAgent'] === 'string' && req.query['userAgent'].trim()
            ? req.query['userAgent'].trim()
            : selectDefaultUserAgent(req.headers['user-agent']);

    // Forward select browser request headers upstream (e.g. Range for seeking)
    const forwardedRequestHeaders: Record<string, string> = {};
    for (const header of FORWARDED_REQUEST_HEADERS) {
        const val = req.headers[header];
        if (typeof val === 'string') {
            forwardedRequestHeaders[header] = val;
        }
    }

    try {
        await proxyStream({
            rawUrl,
            userAgent,
            forwardedRequestHeaders,
            policy,
            req,
            res,
            hopCount: 0,
        });
    } catch (err: unknown) {
        if (res.headersSent) return;
        const message =
            err instanceof Error ? err.message : 'Stream proxy error';
        res.status(502).json({ message, status: 502 });
    }
}

interface ProxyStreamOptions {
    readonly rawUrl: string;
    readonly userAgent?: string;
    readonly forwardedRequestHeaders: Record<string, string>;
    readonly policy: ProviderUrlPolicy;
    readonly req: Request;
    readonly res: Response;
    readonly hopCount: number;
}

async function proxyStream(options: ProxyStreamOptions): Promise<void> {
    const { rawUrl, userAgent, forwardedRequestHeaders, policy, res, hopCount } =
        options;

    // Handle embedded HTTP basic auth if present (e.g. http://user:pass@domain/...)
    let sanitizedRawUrl = rawUrl;
    let basicAuthHeader: string | undefined;
    try {
        const parsed = new URL(rawUrl);
        if (parsed.username || parsed.password) {
            basicAuthHeader =
                'Basic ' +
                Buffer.from(
                    `${decodeURIComponent(parsed.username)}:${decodeURIComponent(parsed.password)}`
                ).toString('base64');
            parsed.username = '';
            parsed.password = '';
            sanitizedRawUrl = parsed.href;
        }
    } catch {
        // let validateProviderUrl report the invalid URL
    }

    // SSRF guard: validate every hop
    const target = await validateProviderUrl(sanitizedRawUrl, policy);
    if ('message' in target) {
        res.status(target.status).json({ message: target.message, status: target.status });
        return;
    }

    const url = target.url;
    const secure = url.protocol === 'https:';
    const hostname = url.hostname.replace(/^\[|\]$/g, '');
    const port = Number(url.port || (secure ? 443 : 80));
    const path = url.pathname + url.search;

    const reqHeaders: Record<string, string> = {
        ...forwardedRequestHeaders,
        Host: url.host,
    };
    if (userAgent) {
        reqHeaders['User-Agent'] = userAgent;
    }
    if (basicAuthHeader && !reqHeaders['Authorization'] && !reqHeaders['authorization']) {
        reqHeaders['Authorization'] = basicAuthHeader;
    }

    const upstream = await new Promise<IncomingMessage>((resolve, reject) => {
        const requestOptions: RequestOptions & { rejectUnauthorized?: boolean } = {
            hostname,
            port,
            path,
            method: 'GET',
            headers: reqHeaders,
            timeout: STREAM_PROXY_TIMEOUT_MS,
            rejectUnauthorized: false,
        };

        const makeRequest = secure ? httpsRequest : httpRequest;
        const clientReq = makeRequest(requestOptions, resolve);
        clientReq.on('error', reject);
        clientReq.on('timeout', () => {
            clientReq.destroy(new Error('Stream proxy upstream timed out'));
        });
        clientReq.end();
    });

    const status = upstream.statusCode ?? 502;

    // Handle redirects
    if (status >= 300 && status < 400) {
        const location = upstream.headers['location'];
        upstream.resume(); // consume and discard body
        if (!location) {
            res.status(502).json({ message: 'Redirect without Location', status: 502 });
            return;
        }
        if (hopCount >= MAX_REDIRECT_HOPS) {
            res.status(502).json({ message: 'Too many redirects', status: 502 });
            return;
        }
        // Resolve relative redirects
        const nextUrl = new URL(location, url.href).href;
        await proxyStream({ ...options, rawUrl: nextUrl, hopCount: hopCount + 1 });
        return;
    }

    if (status < 200 || (status >= 300 && status < 400)) {
        upstream.resume();
        res.status(status).end();
        return;
    }

    // Forward safe response headers
    for (const header of FORWARDED_RESPONSE_HEADERS) {
        const val = upstream.headers[header];
        if (val !== undefined) {
            res.setHeader(header, val);
        }
    }

    // Allow the browser player to load the proxied stream from our origin
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET, HEAD, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Range');
    res.setHeader('Access-Control-Expose-Headers', 'Content-Length, Content-Range, Accept-Ranges');

    res.status(status);

    // For HLS manifests: rewrite segment URLs in the .m3u8 so the browser
    // requests those through the proxy too.
    const contentType = (upstream.headers['content-type'] ?? '').toLowerCase();
    const isM3u =
        contentType.includes('mpegurl') ||
        contentType.includes('x-mpegurl') ||
        contentType.includes('application/vnd.apple.mpegurl') ||
        url.pathname.toLowerCase().endsWith('.m3u8') ||
        url.pathname.toLowerCase().endsWith('.m3u') ||
        url.search.toLowerCase().includes('.m3u8') ||
        url.search.toLowerCase().includes('.m3u');

    if (isM3u) {
        await rewriteAndSendM3u8(upstream, url.href, options.req, res);
        return;
    }

    // For everything else (TS segments, MP4, audio…) pipe directly.
    upstream.pipe(res);
    upstream.on('error', () => {
        if (!res.headersSent) res.status(502).end();
        else res.end();
    });
}

/**
 * Reads an HLS manifest body, rewrites all segment/playlist URLs to go through
 * this proxy, and sends the modified manifest to the browser.
 *
 * This is what makes seeking and multi-bitrate HLS work:
 *   - Every `.ts` segment line becomes `/api/stream-proxy?url=<encoded-ts-url>`
 *   - Every sub-playlist line becomes `/api/stream-proxy?url=<encoded-m3u8-url>`
 *   - Every URI attribute in tags (#EXT-X-KEY, #EXT-X-MEDIA, #EXT-X-MAP) is proxied
 *   - Absolute URIs (http/https) are encoded as-is; relative URIs are resolved
 *     against the manifest's own URL first.
 */
async function rewriteAndSendM3u8(
    upstream: IncomingMessage,
    baseUrl: string,
    req: Request,
    res: Response
): Promise<void> {
    let body = '';
    for await (const chunk of upstream) {
        body += chunk.toString('utf8');
    }

    const proxyBase = buildProxyBase();
    const token = typeof req.query['token'] === 'string' ? req.query['token'] : '';
    const userAgent = typeof req.query['userAgent'] === 'string' ? req.query['userAgent'] : '';
    const extraParams =
        (token ? `&token=${encodeURIComponent(token)}` : '') +
        (userAgent ? `&userAgent=${encodeURIComponent(userAgent)}` : '');

    const rewritten = body
        .split('\n')
        .map((line) => {
            const trimmed = line.trim();
            if (!trimmed) return line;

            // Rewrite URI attributes in HLS tags (#EXT-X-KEY, #EXT-X-MEDIA, #EXT-X-MAP, etc.)
            if (trimmed.startsWith('#')) {
                return line.replace(/URI="([^"]+)"/g, (_match, uri) => {
                    let resolved: string;
                    try {
                        resolved = new URL(uri, baseUrl).href;
                    } catch {
                        return _match;
                    }
                    return `URI="${proxyBase}/stream-proxy?url=${encodeURIComponent(resolved)}${extraParams}"`;
                });
            }

            // Resolve media segment or sub-playlist URL
            let resolved: string;
            try {
                resolved = new URL(trimmed, baseUrl).href;
            } catch {
                return line; // leave malformed lines alone
            }
            return `${proxyBase}/stream-proxy?url=${encodeURIComponent(resolved)}${extraParams}`;
        })
        .join('\n');

    res.setHeader('Content-Type', 'application/vnd.apple.mpegurl');
    res.removeHeader('Content-Length'); // body length changed
    res.send(rewritten);
}

function selectDefaultUserAgent(headerVal: unknown): string {
    if (typeof headerVal === 'string' && headerVal.trim()) {
        const lower = headerVal.toLowerCase();
        if (
            lower.includes('vlc') ||
            lower.includes('kodi') ||
            lower.includes('tivimate') ||
            lower.includes('smarters') ||
            lower.includes('exoplayer') ||
            lower.includes('lavf') ||
            lower.includes('applecoremedia')
        ) {
            return headerVal.trim();
        }
    }
    return 'IPTVSmarters/2.2.2.1';
}

function buildProxyBase(): string {
    // Return root-relative '/api' path so segment requests are resolved against
    // the client's current browser origin, host, and port directly without
    // depending on reverse-proxy header rewrites.
    return '/api';
}
